import type * as app_workbook from '@ankoh/dashql-jsonschema/app_workbook.js';
import type { TopLevelSpec } from 'vega-lite';

import type * as core_buffers from '@ankoh/dashql-core/buffers';

export interface DashboardSpec {
    row?: number | null;
    column?: number | null;
    width?: number | null;
    height?: number | null;
}

/// Script collection type definitions.
///
/// These types represent the runtime state of the workbook's scripts.
/// Storage format types (WorkbookMetadata, WorkbookOriginType) come from JSON Schema.

// Re-export storage format types from JSON Schema
export type WorkbookMetadata = app_workbook.WorkbookMetadata;

/// A query with `@vis` tags resolved against the workbook. Discriminated on the
/// renderer named by the tag: `vegalite` carries a parsed Vega-Lite spec,
/// `markdown` carries the compiled row template.
/// All carry the SQL to execute against the backend and the statement with the tags.
export type ResolvedVisualizeQuery =
    | {
          renderer: 'vegalite';
          // The SQL to execute against the backend
          sql: string;
          // The statement whose @vis tags describe the visualization
          statementId: number;
          // The Vega-Lite spec generated by the analyzer
          vegaLiteSpec: TopLevelSpec;
          dashboardSpec?: DashboardSpec | null;
      }
    | {
          renderer: 'markdown';
          // The SQL to execute against the backend
          sql: string;
          // The statement whose @vis tags describe the visualization
          statementId: number;
          // The row template compiled by dashql-core.
          markdownSpec: core_buffers.visualization.MarkdownSpecT;
          dashboardSpec?: DashboardSpec | null;
      }
    | {
          renderer: 'table';
          // The SQL to execute against the backend
          sql: string;
          // The statement whose @vis tags describe the visualization
          statementId: number;
          dashboardSpec?: DashboardSpec | null;
      };

/// Script annotations derived from analysis
export interface ScriptAnnotations {
    // The table definitions
    tableDefs: string[];
    // The resolved visualization of this script (its @vis tags), if any.
    visualizeQuery: ResolvedVisualizeQuery | null;
    // The placement of the script on the dataflow canvas, its `@flow` tag, if any: a position, a size, or both.
    flowPosition?: FlowPosition | null;
    // The dashboard placement of the script, the `@board` tag of its last statement, if any. A script without a
    // visualization is a collapsed card on the board.
    boardPosition?: BoardPosition | null;
    // Is the last statement a query? Only a query is visualized.
    lastStatementIsQuery?: boolean;
    // Does the script run only on request, its `@manual` tag? Execute All and input changes leave it out.
    manual?: boolean;
}

/// The dashboard placement of a script
export interface BoardPosition extends DashboardSpec {
    // The statement whose annotation holds the `@board` tag
    statementId: number;
}

/// The position of a script on the dataflow canvas
export interface FlowPosition {
    // The statement whose annotation holds the `@flow` tag
    statementId: number;
    // The top left corner of the box, both null if the layout places the box
    x: number | null;
    y: number | null;
    // The width of the box, null for the default width
    width: number | null;
    // The height of the chart of the box, null for the default height
    height: number | null;
}

/// A reference in the workbook's flat ordered script collection.
export interface ScriptRef {
    // The script id
    scriptId: number;
    // The file name (e.g., "extract.sql")
    fileName: string;
}

/// Helper to create empty annotations
export function createEmptyAnnotations(): ScriptAnnotations {
    return {
        tableDefs: [],
        visualizeQuery: null,
        flowPosition: null,
        boardPosition: null,
        lastStatementIsQuery: false,
    };
}

/// Trailing ".sql" extension, stripped for display.
const SCRIPT_EXTENSION_RE = /\.sql$/i;

/// The display name of a script, its file name without the ".sql" extension.
/// "01_extract.sql" -> "01_extract". Used for tab/feed/details labels and to pre-fill the rename input.
export function scriptDisplayName(fileName: string): string {
    return fileName.replace(SCRIPT_EXTENSION_RE, '');
}

/// Helper to create a committed script entry.
export function createScriptRef(scriptId: number, fileName: string): ScriptRef {
    return {
        scriptId,
        fileName,
    };
}
